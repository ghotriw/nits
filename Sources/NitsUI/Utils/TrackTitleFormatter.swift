import Foundation
import NitsCore

public enum TrackTitleFormatter {
    /// Formats an audio track title with localized language name or fallback
    public static func format(title: String, language: String, fallbackId: Int) -> String {
        var parts: [String] = []
        let trimmedTitle = title.trimmingCharacters(in: .whitespacesAndNewlines)
        if !trimmedTitle.isEmpty {
            parts.append(trimmedTitle)
        }

        let trimmedLang = language.trimmingCharacters(in: .whitespacesAndNewlines)
        if !trimmedLang.isEmpty {
            let loc = Locale.current
            if let localized = loc.localizedString(forIdentifier: trimmedLang)
                ?? loc.localizedString(forLanguageCode: trimmedLang)
            {
                if trimmedTitle.range(of: localized, options: .caseInsensitive) == nil {
                    parts.append("[\(localized.capitalized)]")
                }
            } else if trimmedTitle.range(of: trimmedLang, options: .caseInsensitive) == nil {
                parts.append("[\(trimmedLang.uppercased())]")
            }
        }

        if parts.isEmpty {
            parts.append("Track #\(fallbackId)")
        }

        return parts.joined(separator: " ")
    }

    /// A subtitle track's name, with its flags ("English (Forced, SDH)").
    public static func format(_ track: SubtitleTrack) -> String {
        let name = format(title: track.title, language: track.language, fallbackId: track.id + 1)
        // A network file's title may say so already ("English (auto-generated)").
        let isAuto = track.isAutoGenerated && !name.localizedCaseInsensitiveContains("auto")
        let flags = [track.isForced ? "Forced" : nil, track.isSDH ? "SDH" : nil, isAuto ? "Auto" : nil]
            .compactMap { $0 }
        return flags.isEmpty ? name : "\(name) (\(flags.joined(separator: ", ")))"
    }
}
