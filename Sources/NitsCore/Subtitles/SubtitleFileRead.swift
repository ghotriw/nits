import Foundation

/// A local subtitle file, read to be listed as tracks (`SubtitleController.addReadFile`). Reading it opens the file (a
/// sleeping drive, a network volume), probes a bitmap one with FFmpeg and parses a text one whole, so it is done off the
/// main actor; listing it is not.
struct SubtitleFileRead: Sendable {
    enum Content: Sendable {
        /// The bitmap streams of a PGS (`.sup`) or VobSub (`.idx`) file: one per language of an index. Their pictures
        /// are read when a track is selected.
        case bitmap([BitmapStream])
        /// An SRT, WebVTT or ASS file, parsed.
        case document(SubtitleDocument)
        /// A format FFmpeg reads (`FFmpegTextSubtitles`): only its beginning was looked at; it is read when its track
        /// is selected.
        case ffmpegText
    }

    struct BitmapStream: Sendable, Equatable {
        var index: Int
        /// Empty when the file doesn't tell.
        var language: String
    }

    /// The file the tracks are made from, standardized: the `.idx` of a VobSub `.sub`.
    var url: URL
    /// `nil` when it can't be read.
    var content: Content?

    /// Reads the local file at `url`, listed as `file` says when given (its language guides the text encoding);
    /// `encoding` is the user's choice for files that aren't Unicode. Blocks.
    nonisolated static func read(
        _ url: URL, file: MediaLoadRequest.SubtitleFile? = nil, encoding: String.Encoding?
    ) -> SubtitleFileRead {
        read(target: target(of: url), file: file, encoding: encoding)
    }

    /// The file the tracks of the local file at `url` are made from, standardized (`url`): a VobSub `.sub` loads
    /// through its `.idx`, whichever of the two was picked. One with no index is MicroDVD or SubViewer text, which
    /// FFmpeg reads (VobSub data on its own reads as none). Looks for the index on disk.
    nonisolated static func target(of url: URL) -> URL {
        (SidecarSubtitles.vobSubIndex(forDataFile: url) ?? url).standardizedFileURL
    }

    /// `read(_:file:encoding:)` of a file already resolved by `target(of:)`.
    nonisolated static func read(
        target url: URL, file: MediaLoadRequest.SubtitleFile?, encoding: String.Encoding?
    ) -> SubtitleFileRead {
        if SidecarSubtitles.isBitmapSubtitleFile(url) {
            let streams = EmbeddedSubtitleReader.bitmapSubtitleStreams(of: url).map {
                BitmapStream(index: $0.index, language: $0.language)
            }
            guard !streams.isEmpty else {
                AppLog.error(.subtitles, "No bitmap subtitle stream in \(url)")
                return SubtitleFileRead(url: url, content: nil)
            }
            return SubtitleFileRead(url: url, content: .bitmap(streams))
        }

        let hints = SubtitleController.textEncodingHints(for: url, language: file?.language, encoding: encoding)
        let fileExtension = url.pathExtension.lowercased()
        if FFmpegTextSubtitles.extensions.contains(fileExtension) {
            guard FFmpegTextSubtitles.isReadable(url, hints: hints) else {
                AppLog.warning(
                    .subtitles, "No subtitles in a format FFmpeg reads (MicroDVD, SubViewer, SAMI) in \(url.path)")
                return SubtitleFileRead(url: url, content: nil)
            }
            return SubtitleFileRead(url: url, content: .ffmpegText)
        }
        guard let data = try? Data(contentsOf: url),
            let document = SubtitleController.parseTextSubtitle(
                data: data, url: url, format: isASS(url, file: file) ? .ass : .text,
                collapsingRollUp: file?.isAutoGenerated == true, hints: hints)
        else {
            AppLog.error(.subtitles, "Unable to decode subtitle file with supported encodings: \(url)")
            return SubtitleFileRead(url: url, content: nil)
        }
        return SubtitleFileRead(url: url, content: .document(document))
    }

    /// Whether the text file at `url` is ASS by its name, or as `file` declares it.
    nonisolated static func isASS(_ url: URL, file: MediaLoadRequest.SubtitleFile?) -> Bool {
        let fileExtension = url.pathExtension.lowercased()
        return fileExtension == "ass" || fileExtension == "ssa" || file?.format == .ass
    }
}

/// Local subtitle files read together (`read(_:isCancelled:)`): those a media takes when it loads, read before the load
/// is applied (off the main actor for a background load), or those added to it (`SubtitleController.addExternal`).
struct MediaSubtitleFiles: Sendable {
    /// What to read.
    struct Lookup: Sendable {
        /// The request's or page's files, or those added; only the local ones are read.
        var requested: [MediaLoadRequest.SubtitleFile] = []
        /// The media's path, next to which files named as it are its subtitles (`SidecarSubtitles`); `nil` for none.
        var sidecarsOf: String?
        /// The file the history saved for the media, when one was selected.
        var savedPath: String?
        /// The user's choice for files that aren't Unicode.
        var encoding: String.Encoding?
        /// Files already listed as tracks (`SubtitleTrack.externalURL`): not read again.
        var listed: Set<URL> = []
    }

    /// The file each URL asked by (standardized) is read as (`SubtitleFileRead.target`).
    private var targets: [URL: URL] = [:]
    /// The files read, by `targets`: a VobSub `.sub` and its `.idx` are read once.
    private var reads: [URL: SubtitleFileRead] = [:]
    /// Those found next to the media, in order.
    private(set) var sidecars: [URL] = []

    init() {}

    /// The file read for `url`; `nil` if it wasn't one of those looked for, or was listed already (`target(of:)`).
    subscript(_ url: URL) -> SubtitleFileRead? {
        target(of: url).flatMap { reads[$0] }
    }

    /// The file `url` was read as, or would have been when listed already; `nil` if it wasn't looked for.
    func target(of url: URL) -> URL? {
        targets[url.standardizedFileURL]
    }

    /// Finds and reads the files `lookup` tells of, until `isCancelled`. Blocks: it lists the media's folder and reads
    /// every file.
    nonisolated static func read(
        _ lookup: Lookup, isCancelled: @Sendable () -> Bool = { false }
    ) -> MediaSubtitleFiles {
        var files = MediaSubtitleFiles()
        func read(_ url: URL, file: MediaLoadRequest.SubtitleFile? = nil) {
            let key = url.standardizedFileURL
            guard files.targets[key] == nil, !isCancelled() else { return }
            let target = SubtitleFileRead.target(of: url)
            files.targets[key] = target
            guard files.reads[target] == nil, !lookup.listed.contains(target) else { return }
            files.reads[target] = SubtitleFileRead.read(target: target, file: file, encoding: lookup.encoding)
        }
        for file in lookup.requested where file.url.isFileURL {
            read(file.url, file: file)
        }
        if let path = lookup.sidecarsOf, !isCancelled() {
            let mediaURL = URL(string: path).flatMap { $0.isFileURL ? $0 : nil } ?? URL(fileURLWithPath: path)
            files.sidecars = SidecarSubtitles.urls(for: mediaURL)
            for url in files.sidecars { read(url) }
        }
        // One that moved since is left out: the history's choice is then left to `TrackAutoSelection`.
        if let path = lookup.savedPath, !isCancelled(), FileManager.default.fileExists(atPath: path) {
            read(URL(fileURLWithPath: path))
        }
        return files
    }
}
